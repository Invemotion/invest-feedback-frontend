// lib/ai/prompt_builder.dart
import 'dart:convert';

class PromptBuilder {
  static String buildPrompt(Map<String, dynamic> payload) {
    final reportDate = (payload['report_date'] ?? '날짜미제공').toString();
    final tickerName = (payload['ticker']?['name'] ?? '종목미제공').toString();

    const rules = r'''
[작성 원칙 — 반드시 준수]
1) 수치 우선: 가격(원), 수량(주), 시간(시:분), 퍼센트(%)를 최대한 표기. 임의 추정 금지. 입력에 없으면 '데이터 미제공'.
2) 근거 각주: 문장 끝에 근거를 짧게 표기. 예) [거래 10:22], [뉴스 05:00], [시세 ±30m 윈도우], [일지 tradeId=1].
3) 분석 구조: (계획)→(실행)→(결과)→(원인/대안) 순서로 요약. 감정·행동 태그는 ‘원인/대안’에 연결.
4) 금지 표현: 칭찬/과장/확신성 금지. 보고서 톤.
5) 문체: 한 항목 1~2문장, 불릿 위주.
6) 템플릿 섹션/제목은 그대로.
7) 뉴스는 시간대별 묶음 요약(가능한 경우). 데이터 없으면 '데이터 미제공'.
''';

    final template = '''
# $reportDate 일일 투자 리포트

## 0) 오늘의 한 줄
- 포트 수익률: **데이터 미제공** / 지수: **데이터 미제공** → 일일 초과수익 **데이터 미제공**
- 대표 트레이드 1건 요약(가격/수량/시간, 근거 각주 포함).

---
## 1) 오늘의 거래 요약
- **총 n건**: 매수 x, 매도 y  
- **체결 상태**: 당일 청산 a, **보유 중 b**  
- **실현 손익**: 이익 p건, 손실 q건, 본전 r건, 미확정 k건  
- **대표 트레이드**: 체결가·수량·체결시각·손익 유형. [거래 근거]

(계획↔실행↔결과)
- 계획: 목표가/손절/시간 규율. [일지/거래]
- 실행: 실제 체결가·수량·시간, 계획 대비 차이. [거래]
- 결과: 손익 유형과 수치. [거래/시세]

---
## 2) 감정·행동 패턴
- 상위 감정/행동 태그와 건수. [일지]
- 의사결정에 미친 경로 1~2문장. [일지/거래]
- 개선 가이드 1~2개(수치 포함).

---
## 3) 투자 성향 프로필 대비 점검
- 위험 성향/손실 허용/목표와 실행 간 합치/이탈 3~4줄. [프로필/거래]
- 사이징/시간규율/테마 민감도 리스크 1~2줄.

---
## 4) 시장 환경·뉴스
- 시세(일중/일봉): 레인지·변동률·거래량 특이점. [시세]
- $tickerName 관련 시간대 묶음 뉴스 요약(가능 시).

---
## 5) 오늘의 키 인사이트 (재현 가능)
- 불릿 3~5개: '상황→행동→결과→교훈', 수치·트리거 포함. [각 근거]

---
## 6) 투자 원칙(요지) — 오늘 케이스
- 매수/손절/익절/시간 손절/사이징/레짐/이벤트/분산 각 1줄.
''';

    final instructions = '''
당신은 한국어 리서치 애널리스트입니다. 아래 JSON(payload)을 바탕으로 '$tickerName' 중심의 **일일 리포트**를 작성하세요.

$rules

[템플릿 — 이 형식을 그대로 채울 것]
$template

[입력(JSON)]
${jsonEncode(payload)}
''';

    return instructions;
  }
}
